function playCorrectDingThenSentence(source) {
  stopCurrentAudio();
  const token = playbackToken;

  playCorrectDing(() => {
    if (token === playbackToken) {
      playAudio(source);
    }
  });
}

function playCorrectDing(onEnded) {
  const AudioContext = window.AudioContext || window.webkitAudioContext;

  if (!AudioContext) {
    onEnded();
    return;
  }

  const context = new AudioContext();
  currentDingContext = context;
  const gain = context.createGain();
  const firstTone = context.createOscillator();
  const secondTone = context.createOscillator();
  const now = context.currentTime;

  gain.connect(context.destination);
  gain.gain.setValueAtTime(0.0001, now);
  gain.gain.exponentialRampToValueAtTime(0.22, now + 0.015);
  gain.gain.exponentialRampToValueAtTime(0.0001, now + 0.38);

  firstTone.type = "sine";
  firstTone.frequency.setValueAtTime(660, now);
  firstTone.connect(gain);
  firstTone.start(now);
  firstTone.stop(now + 0.18);

  secondTone.type = "sine";
  secondTone.frequency.setValueAtTime(880, now + 0.12);
  secondTone.connect(gain);
  secondTone.start(now + 0.12);
  secondTone.stop(now + 0.38);

  secondTone.addEventListener("ended", () => {
    if (currentDingContext === context) {
      currentDingContext = null;
    }
    context.close().catch(() => {});
    onEnded();
  }, { once: true });
}

function stopCurrentAudio(options = {}) {
  playbackToken += 1;
  if (!options.keepStorySequence) {
    storySequence.token += 1;
    storySequence.audio = null;
    storySequence.paused = false;
    storySequence.finished = true;
    clearStorySequenceHighlight();
    const activeLesson = lessons.find((lesson) => lesson.id === storySequence.lessonId);
    if (activeLesson) {
      updateStorySequenceControls("ready", activeLesson);
    }
  }
  resetAudioButton();
  currentAudioButton = null;

  if (!currentAudio) {
    if (currentDingContext) {
      currentDingContext.close().catch(() => {});
      currentDingContext = null;
    }
    return;
  }

  currentAudio.pause();
  currentAudio.currentTime = 0;
  currentAudio = null;

  if (currentDingContext) {
    currentDingContext.close().catch(() => {});
    currentDingContext = null;
  }
}

async function initializeApp() {
  renderLoading();

  try {
    await handleAuthRedirect();
  } catch (error) {
    console.error(error);
    renderAuthGate("Sign-in could not be completed. Please try again.");
    return;
  }

  if (!getCurrentUser()) {
    renderAuthGate();
    return;
  }

  await loadRemoteLessons();
  await loadCloudState();
  render();
}

window.addEventListener("hashchange", () => {
  queueCloudStateSave();
  render();
});
window.addEventListener("visibilitychange", () => {
  if (document.visibilityState === "hidden" && getCurrentUser()) {
    saveCloudStateNow(undefined, { keepalive: true }).catch(() => {});
  }
});
initializeApp();
