function render() {
  if (!getCurrentUser()) {
    renderAuthGate();
    return;
  }

  const route = window.location.hash.replace("#", "");
  const routeItem = getItem(route);

  if (route === "history") {
    renderHistory();
    renderAccountControls();
    return;
  }

  if (route === "fluency") {
    renderFluencyHome();
    renderAccountControls();
    return;
  }

  if (route === "fluency-weak-review") {
    renderFluencyWeakReview();
    renderAccountControls();
    return;
  }

  const toolRoute = getToolRoute(route);
  if (toolRoute) {
    renderToolPlaceholder(toolRoute);
    renderAccountControls();
    return;
  }

  const fluencyRoute = getFluencyRoute(route);

  if (fluencyRoute) {
    renderFluencyLesson(fluencyRoute);
    renderAccountControls({ hideActions: true });
    return;
  }

  if (route === "intro") {
    renderIntro(courseItems[0]);
    renderAccountControls();
    return;
  }

  if (routeItem?.type === "lesson") {
    renderLockedAwareLesson(routeItem);
    renderAccountControls({ hideActions: true });
    return;
  }

  const testRoute = getTestRoute(route);

  if (testRoute) {
    if (!isItemUnlocked(testRoute.lesson.id)) {
      renderLockedItem(testRoute.lesson);
      renderAccountControls({ hideActions: true });
      return;
    }

    if (!isLessonTestUnlocked(testRoute.lesson)) {
      renderLesson(testRoute.lesson);
      renderAccountControls({ hideActions: true });
      return;
    }

    if (testRoute.testIndex === 0) {
      renderPartOneIntro(testRoute.lesson, testRoute.test);
    } else {
      renderFillIntro(testRoute.lesson, testRoute.test);
    }
    renderAccountControls({ hideActions: true });
    return;
  }

  renderHome();
  renderAccountControls();
}

